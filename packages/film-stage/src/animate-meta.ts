export function fitAnimationLengths(inLen: number, outLen: number, span: number): [number, number] {
  const a = Math.max(0, inLen),
    b = Math.max(0, outLen),
    max = Math.max(0, span),
    total = a + b;
  if (!total || total <= max) return [a, b];
  const scale = max / total;
  return [a * scale, b * scale];
}
